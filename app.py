@app.route('/admin/manage_admins', methods=['GET', 'POST'])
def manage_admins():
    if 'admin_id' not in session or session.get('admin_type') not in ['superadmin', 'zonal_superadmin']:
        return redirect(url_for('admin_dashboard'))
        
    if request.method == 'POST':
        username = request.form.get('username')
        password = request.form.get('password')
        hashed_pw = generate_password_hash(password) 
        
        user_type = request.form.get('user_type')
        if session.get('admin_type') == 'zonal_superadmin' and user_type in ['superadmin', 'zonal_superadmin']:
            return render_template('manage_admins.html', error="You cannot create admins of equal or higher rank.")
            
        new_admin = Admin(
            username=username,
            password=hashed_pw,
            full_name=request.form.get('full_name'),
            email=request.form.get('email'),
            zone=request.form.get('zone', session.get('zone')),
            division=request.form.get('division', 'ALL'),
            lobby=request.form.get('lobby', 'ALL'),
            user_type=user_type,
            created_by=session['admin_id']
        )
        db.session.add(new_admin)
        db.session.commit()
        return redirect(url_for('manage_admins'))
        
    if session.get('admin_type') == 'superadmin':
        admins = Admin.query.all()
    else:
        admins = Admin.query.filter_by(zone=session.get('zone')).all()
        
    return render_template('manage_admins.html', admins=admins)

