@app.route('/admin/register_candidate', methods=['GET', 'POST'])
def register_candidate():
    if 'admin_id' not in session:
        return redirect(url_for('admin_login'))
        
    admin_type = session.get('admin_type')
    admin = Admin.query.get(session['admin_id'])
    
    if request.method == 'POST':
        # --- THE 5-TIER HIERARCHY LOGIC ---
        if admin_type == 'superadmin':
            zone = request.form.get('zone')
            division = request.form.get('division')
            lobby = request.form.get('lobby')
        elif admin_type == 'zonal_superadmin':
            zone = admin.zone
            division = request.form.get('division')
            lobby = request.form.get('lobby')
        elif admin_type == 'division_admin':
            zone = admin.zone
            division = admin.division
            lobby = request.form.get('lobby')
        else:
            zone = admin.zone
            division = admin.division
            lobby = admin.lobby

        new_candidate = Candidate(
            lobby_id=request.form.get('lobby_id'),
            candidate_name=request.form.get('candidate_name'),
            zone=zone,
            division=division,
            lobby=lobby,
            post=request.form.get('post'),
            email=request.form.get('email'),
            phone=request.form.get('phone'),
            created_by=admin.id
        )
        
        try:
            db.session.add(new_candidate)
            db.session.commit()
            log_audit(admin.id, admin_type, 'Register Candidate', f"Assigned to {zone}/{division}/{lobby}", request.remote_addr)
            return render_template('register_candidate.html', success=f"Candidate Registered to {zone}/{division}/{lobby}!")
        except Exception as e:
            db.session.rollback()
            return render_template('register_candidate.html', error="Error: Lobby ID already exists.")
            
    return render_template('register_candidate.html')

