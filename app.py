@app.route('/api/save_test_result', methods=['POST'])
def save_test_result():
    if 'candidate_id' not in session: 
        return jsonify({'success': False, 'message': 'Not logged in'})
    
    data = request.get_json()
    start_time = session.get('test_start_time', datetime.utcnow().timestamp())
    time_taken = int(datetime.utcnow().timestamp() - start_time)
    result_status = 'pass' if data['passed'] else 'fail'
    
    new_attempt = TestAttempt(
        candidate_id=session['candidate_id'],
        lobby_id=session.get('lobby_id'),
        test_id=data['test_id'],
        score=data['score_obtained'],
        max_score=data['max_score'],
        percentage=data['percentage'],
        result=result_status,
        time_taken=time_taken
    )
    db.session.add(new_attempt)
    db.session.commit()
    
    candidate = Candidate.query.get(session['candidate_id'])
    if candidate.test_status == 'not_started':
        candidate.test_status = 'in_progress'
        db.session.commit()
    
    session.pop('test_start_time', None)
    return jsonify({'success': True, 'attempt_id': new_attempt.id})

