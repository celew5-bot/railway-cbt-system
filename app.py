@app.route('/admin/view_results')
def view_results():
    if 'admin_id' not in session: return redirect(url_for('admin_login'))
    
    query = db.session.query(TestAttempt, Candidate, Test)\
        .join(Candidate, TestAttempt.candidate_id == Candidate.id)\
        .join(Test, TestAttempt.test_id == Test.id)
        
    admin_type = session.get('admin_type')
    if admin_type != 'superadmin':
        if admin_type == 'zonal_superadmin':
            query = query.filter(Candidate.zone == session.get('zone'))
        elif admin_type == 'division_admin':
            query = query.filter(Candidate.division == session.get('division'))
        else:
            query = query.filter(Candidate.lobby == session.get('lobby'))
            
    results = query.order_by(TestAttempt.attempt_date.desc()).all()
    return render_template('view_results.html', results=results)

