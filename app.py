@app.route('/candidate/test_selection')
def test_selection():
    if 'candidate_id' not in session: 
        return redirect(url_for('candidate_login'))
    
    tests = Test.query.filter_by(status='active').order_by(Test.test_number).all()
    attempts = TestAttempt.query.filter_by(candidate_id=session['candidate_id']).all()
    attempted_tests = [a.test_id for a in attempts]
    
    completed_count = len(set(attempted_tests))
    total_tests = len(tests)
    progress_pct = (completed_count / total_tests * 100) if total_tests > 0 else 0
    all_completed = completed_count >= total_tests if total_tests > 0 else False
    
    return render_template('test_selection.html', 
                           tests=tests, 
                           attempted_tests=attempted_tests,
                           completed_count=completed_count,
                           total_tests=total_tests,
                           progress_pct=progress_pct,
                           all_completed=all_completed)

@app.route('/test_interface/<int:test_id>')
def test_interface(test_id):
    if 'candidate_id' not in session: return redirect(url_for('candidate_login'))
    
    test = Test.query.get_or_404(test_id)
    g13_questions, g13_error = [], ""
    
    if test.test_number == 13:
        csv_path = os.path.join(app.root_path, 'g13_questions.csv')
        try:
            with open(csv_path, mode='r', encoding='utf-8') as file:
                reader = csv.reader(file)
                next(reader, None) # Skip Header
                for row in reader:
                    if len(row) >= 6 and row[1].strip():
                        g13_questions.append({
                            'q': row[1].strip(),
                            'optA': row[2].strip() if len(row) > 2 else '',
                            'optB': row[3].strip() if len(row) > 3 else '',
                            'optC': row[4].strip() if len(row) > 4 else '',
                            'ans': row[5].strip().upper() if len(row) > 5 else 'A'
                        })
        except Exception as e:
            g13_error = f"Error reading CSV: {str(e)}"

    session['test_start_time'] = datetime.utcnow().timestamp()
    
    return render_template('test_interface.html', 
                           test=test, 
                           g13_data=json.dumps(g13_questions), 
                           g13_error=g13_error)

