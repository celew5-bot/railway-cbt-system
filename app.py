@app.route('/candidate/login', methods=['GET', 'POST'])
def candidate_login():
    if request.method == 'POST':
        lobby_id = request.form.get('lobby_id')
        name = request.form.get('candidate_name')
        phone = request.form.get('phone')
        post = request.form.get('post')
        
        candidate = Candidate.query.filter_by(lobby_id=lobby_id, candidate_name=name, phone=phone, post=post).first()
        
        if candidate:
            session['candidate_id'] = candidate.id
            session['candidate_name'] = candidate.candidate_name
            session['lobby_id'] = candidate.lobby_id
            session['zone'] = candidate.zone
            session['post'] = candidate.post
            log_audit(candidate.id, 'candidate', 'Candidate Login', f"Lobby ID: {lobby_id}", request.remote_addr)
            return redirect(url_for('test_selection'))
        return render_template('candidate_login.html', error="Invalid Details. Ensure exact match.")
    return render_template('candidate_login.html')

@app.route('/admin/login', methods=['GET', 'POST'])
def admin_login():
    if request.method == 'POST':
        username = request.form.get('username')
        password = request.form.get('password')
        admin = Admin.query.filter_by(username=username, status='active').first()
        
        if admin:
            is_valid = False
            stored_hash = admin.password
            
            # --- THE PHP TO PYTHON PASSWORD TRANSLATOR ---
            if stored_hash.startswith('$2y$'):
                # Python's bcrypt expects $2a$ or $2b$. We safely swap the PHP $2y$ prefix.
                compatible_hash = stored_hash.replace('$2y$', '$2a$').encode('utf-8')
                try:
                    is_valid = bcrypt.checkpw(password.encode('utf-8'), compatible_hash)
                except Exception as e:
                    print(f"Bcrypt error: {e}")
            else:
                # Handle new passwords generated by Python/Werkzeug
                try:
                    is_valid = check_password_hash(stored_hash, password)
                except ValueError:
                    is_valid = False
            
            if is_valid:
                session['admin_id'] = admin.id
                session['admin_name'] = admin.full_name
                session['admin_type'] = admin.user_type
                session['zone'] = admin.zone
                session['division'] = admin.division
                session['lobby'] = admin.lobby
                
                admin.last_login = datetime.utcnow()
                db.session.commit()
                log_audit(admin.id, admin.user_type, 'Admin Login', 'Successful', request.remote_addr)
                return redirect(url_for('admin_dashboard'))
                
        return render_template('admin_login.html', error="Invalid Credentials")
    return render_template('admin_login.html')

